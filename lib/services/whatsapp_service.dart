import 'package:intl/intl.dart';
import 'package:url_launcher/url_launcher.dart';
import '../models/mobiboss_models.dart';
import 'phone_helper.dart';

class WhatsAppService {
  static final _currencyFormatter = NumberFormat('#,##0.00', 'en_US');
  static final _timeFormatter = DateFormat('h:mm a');
  static final _dateFormatter = DateFormat('EEE, d MMM yyyy');

  /// Formats a complete ShiftRecord into a clean, WhatsApp-friendly audit message.
  static String formatShiftReport({
    required ShiftRecord shift,
    required ShopProfile shopProfile,
    String? tellerName,
  }) {
    final isBalanced = shift.status == 'BALANCED';
    final isShortage = shift.status == 'SHORTAGE';
    final statusEmoji = isBalanced ? '🟢' : (isShortage ? '🔴' : '🔵');
    final varianceSign = shift.cashVariance >= 0 ? '+' : '-';

    final buffer = StringBuffer();
    buffer.writeln('🏪 *${shopProfile.shopName.toUpperCase()}*');
    buffer.writeln('📍 Location: ${shopProfile.branchLocation}');
    if (tellerName != null && tellerName.isNotEmpty) {
      buffer.writeln('👤 Attendant: $tellerName');
    }
    buffer.writeln('🔢 *Shift #${shift.shiftNumber} Audit Report*');
    buffer.writeln('📅 Date: ${_dateFormatter.format(shift.endTime)}');
    buffer.writeln('🕒 Time: ${_timeFormatter.format(shift.startTime)} ➔ ${_timeFormatter.format(shift.endTime)}');
    buffer.writeln('━━━━━━━━━━━━━━━━━━━━━');
    buffer.writeln('💵 *PHYSICAL DRAWER RECONCILIATION*');
    buffer.writeln('• Opening Float: GHS ${_currencyFormatter.format(shift.openingCash)}');
    buffer.writeln('• Expected Drawer: GHS ${_currencyFormatter.format(shift.expectedCash)}');
    buffer.writeln('• Counted Drawer: *GHS ${_currencyFormatter.format(shift.closingCash)}*');
    buffer.writeln('• Status: $statusEmoji *${shift.status}* ($varianceSign GHS ${_currencyFormatter.format(shift.cashVariance.abs())})');
    buffer.writeln('━━━━━━━━━━━━━━━━━━━━━');
    buffer.writeln('📱 *MOBILE MONEY SUMMARY*');
    buffer.writeln('• Deposits (Cash In): GHS ${_currencyFormatter.format(shift.totalCashIn)}');
    buffer.writeln('• Withdrawals (Cash Out): GHS ${_currencyFormatter.format(shift.totalCashOut)}');
    buffer.writeln('• Earned Commissions: *GHS ${_currencyFormatter.format(shift.totalCommissions)}*');
    buffer.writeln('• Total Scanned Txns: *${shift.transactionCount} transactions*');

    if (shift.networkBreakdown != null && shift.networkBreakdown!.isNotEmpty) {
      buffer.writeln('━━━━━━━━━━━━━━━━━━━━━');
      buffer.writeln('📶 *CARRIER BREAKDOWN*');
      for (final entry in shift.networkBreakdown!.entries) {
        final summary = entry.value;
        if (summary.txCount > 0) {
          final netName = _getNetworkDisplayName(summary.network);
          buffer.writeln('• $netName: GHS ${_currencyFormatter.format(summary.netVolume)} (${summary.txCount} txns)');
        }
      }
    }

    if (shift.aiDiagnosis.isNotEmpty) {
      buffer.writeln('━━━━━━━━━━━━━━━━━━━━━');
      buffer.writeln('🤖 *AUDIT DIAGNOSIS*');
      buffer.writeln(shift.aiDiagnosis);
    }

    buffer.writeln('━━━━━━━━━━━━━━━━━━━━━');
    buffer.writeln('_Generated by MobiBoss Ghana_ 🇬🇭');

    return buffer.toString();
  }

  /// Formats live ReconciliationResult before shift is officially closed
  static String formatLiveReconciliationReport({
    required ReconciliationResult result,
    required ShopProfile shopProfile,
    required int shiftNumber,
    required String timeRangeDisplay,
    String? tellerName,
  }) {
    final isBalanced = result.status == 'BALANCED';
    final isShortage = result.status == 'SHORTAGE';
    final statusEmoji = isBalanced ? '🟢' : (isShortage ? '🔴' : '🔵');
    final varianceSign = result.cashVariance >= 0 ? '+' : '-';

    final buffer = StringBuffer();
    buffer.writeln('🏪 *${shopProfile.shopName.toUpperCase()}*');
    buffer.writeln('📍 Location: ${shopProfile.branchLocation}');
    if (tellerName != null && tellerName.isNotEmpty) {
      buffer.writeln('👤 Attendant: $tellerName');
    }
    buffer.writeln('🔢 *Shift #$shiftNumber Live Balance*');
    buffer.writeln('🕒 Range: $timeRangeDisplay');
    buffer.writeln('━━━━━━━━━━━━━━━━━━━━━');
    buffer.writeln('💵 *DRAWER RECONCILIATION*');
    buffer.writeln('• Counted Drawer: *GHS ${_currencyFormatter.format(result.physicalCashCount)}*');
    buffer.writeln('• Expected Drawer: GHS ${_currencyFormatter.format(result.expectedPhysicalCash)}');
    buffer.writeln('• Status: $statusEmoji *${result.status}* ($varianceSign GHS ${_currencyFormatter.format(result.cashVariance.abs())})');
    buffer.writeln('━━━━━━━━━━━━━━━━━━━━━');
    buffer.writeln('📱 *TRANSACTION FLOW*');
    buffer.writeln('• Deposits (Cash In): GHS ${_currencyFormatter.format(result.totalCashIn)}');
    buffer.writeln('• Withdrawals (Cash Out): GHS ${_currencyFormatter.format(result.totalCashOut)}');
    if (result.totalPettyCash > 0) {
      buffer.writeln('• Petty Cash Spent: GHS ${_currencyFormatter.format(result.totalPettyCash)}');
    }
    buffer.writeln('• Commissions: *GHS ${_currencyFormatter.format(result.totalCommissions)}*');

    if (result.networkBreakdown != null && result.networkBreakdown!.isNotEmpty) {
      buffer.writeln('━━━━━━━━━━━━━━━━━━━━━');
      buffer.writeln('📶 *CARRIER BREAKDOWN*');
      for (final entry in result.networkBreakdown!.entries) {
        final summary = entry.value;
        if (summary.txCount > 0) {
          final netName = _getNetworkDisplayName(summary.network);
          buffer.writeln('• $netName: GHS ${_currencyFormatter.format(summary.netVolume)} (${summary.txCount} txns)');
        }
      }
    }

    if (result.aiDiagnosis.isNotEmpty) {
      buffer.writeln('━━━━━━━━━━━━━━━━━━━━━');
      buffer.writeln('🤖 *AUDIT DIAGNOSIS*');
      buffer.writeln(result.aiDiagnosis);
    }

    buffer.writeln('━━━━━━━━━━━━━━━━━━━━━');
    buffer.writeln('_Generated by MobiBoss Ghana_ 🇬🇭');

    return buffer.toString();
  }

  /// Sends the formatted message via WhatsApp to the Owner's phone
  static Future<bool> sendWhatsAppReport({
    required String message,
    required String recipientPhone,
  }) async {
    final cleanPhone = PhoneHelper.toInternational(recipientPhone);
    final encodedMessage = Uri.encodeComponent(message);

    // 1. Try deep link directly to WhatsApp app
    final nativeUri = Uri.parse('whatsapp://send?phone=$cleanPhone&text=$encodedMessage');
    if (await canLaunchUrl(nativeUri)) {
      return await launchUrl(nativeUri, mode: LaunchMode.externalApplication);
    }

    // 2. Try web wa.me URL
    final webUri = Uri.parse('https://wa.me/$cleanPhone?text=$encodedMessage');
    if (await canLaunchUrl(webUri)) {
      return await launchUrl(webUri, mode: LaunchMode.externalApplication);
    }

    // 3. Fallback to generic share url
    final apiUri = Uri.parse('https://api.whatsapp.com/send?phone=$cleanPhone&text=$encodedMessage');
    if (await canLaunchUrl(apiUri)) {
      return await launchUrl(apiUri, mode: LaunchMode.externalApplication);
    }

    return false;
  }

  static String _getNetworkDisplayName(NetworkProvider net) {
    switch (net) {
      case NetworkProvider.mtn:
        return 'MTN MoMo';
      case NetworkProvider.telecel:
        return 'Telecel Cash';
      case NetworkProvider.at:
        return 'AT Money';
      case NetworkProvider.gmoney:
        return 'G-Money';
    }
  }
}
